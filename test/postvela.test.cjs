const test = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs/promises')
const path = require('node:path')
const os = require('node:os')
const { Store } = require('../src/store.cjs')
const { Sources, article } = require('../src/sources.cjs')
const { inspect } = require('../src/postvela.cjs')

test('private Obsidian and HTML comments never become publication copy', () => {
  const value = article('---\ntitle: 公开标题\n---\n# 公开标题\n正文 %%私密备注%% 继续\n<!-- 内部 -->\n结尾\n%%未闭合的私密备注', '主稿.md')
  assert.equal(value.title, '公开标题')
  assert.equal(value.body, '正文  继续\n\n结尾')
})
async function setup(t) {
  const root = await fs.mkdtemp(path.join(os.tmpdir(), 'fatio-postvela-'))
  const store = new Store(':memory:')
  t.after(async () => {store.db.close(); await fs.rm(root, {recursive:true,force:true,maxRetries:3})})
  const sources = new Sources(store, path.join(root,'videos'), null)
  sources.bind('local', root)
  sources.bind('vault', root)
  return {root,store,sources}
}
test('GIF source import fails before creating incomplete drafts or touching assets', async t => {
  const {root,store,sources} = await setup(t)
  await fs.writeFile(path.join(root,'主稿.md'), '---\ntype: content\n---\n# 标题\n![图](demo.gif)')
  await assert.rejects(sources.load('vault','主稿.md'), /GIF 动图/)
  assert.equal(store.snapshot().drafts.length,0)
  assert.equal(store.db.prepare('SELECT count(*) AS n FROM assets').get().n,0)
})
test('hidden images are not imported and backup manuscripts are not selected', async t => {
  const {root,sources} = await setup(t)
  await fs.writeFile(path.join(root,'主稿.md'), '---\ntype: content\n---\n# 标题\n正文\n%%\n![[missing.gif]]\n![[missing.png]]\n%%')
  const draft=await sources.load('vault','主稿.md')
  assert.equal(draft.body,'正文')
  const p=path.join(root,'旧项目')
  await fs.mkdir(p)
  await fs.writeFile(path.join(p,'主稿备份.md'),'不是当前稿')
  await fs.writeFile(path.join(p,'PROJECT.md'),'说明')
  assert.equal((await sources.list('local')).items.length,0)
})
test('PostVela discovery preserves numeric order and missing Live pairs fail visibly', async t => {
  const {root,sources} = await setup(t)
  const p=path.join(root,'projects','一期','动态导出','本次')
  await fs.mkdir(path.join(p,'page-002.pvt'),{recursive:true})
  await fs.writeFile(path.join(p,'图文索引.md'),'# 图集')
  await fs.writeFile(path.join(p,'发布文案.txt'),'完整标题\n\n正文\n\n#标签')
  for(const n of ['page-001.png','page-002.png','page-002-预览.mp4','page-002.pvt/photo.JPG','page-002.pvt/video.MOV','page-002.pvt/metadata.plist'])
    await fs.writeFile(path.join(p,n),'fixture')
  const list=await sources.list('postvela')
  assert.equal(list.items.length,1)
  const pack=await sources.openPostvela(list.items[0].key)
  assert.deepEqual(pack.pages.map(p=>[p.number,p.kind]),[[1,'static'],[2,'live']])
  assert.equal(pack.body,'正文\n\n#标签')
  await fs.unlink(path.join(p,'page-002.pvt/video.MOV'))
  await assert.rejects(sources.openPostvela(list.items[0].key),/配对文件不完整/)
  await assert.rejects(sources.sourceFile('postvela','../outside.md'),/来源项目无效/)
})
test('PostVela rejects gaps and dynamic pages without a static fallback', async t => {
  const {root}=await setup(t)
  await fs.writeFile(path.join(root,'发布文案.txt'),'标题\n正文')
  await fs.writeFile(path.join(root,'page-001.png'),'fixture')
  await fs.mkdir(path.join(root,'page-002.pvt'))
  await assert.rejects(inspect(root,root),/缺少备用 PNG/)
  await fs.writeFile(path.join(root,'page-003.png'),'fixture')
  await assert.rejects(inspect(root,root),/页码不连续/)
})
